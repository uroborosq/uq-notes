#!/bin/bash
# Замер процессорного времени в простое.
#
# Требование «в простое кадров нет» (openspec/specs/idle-power) проверяется
# этим замером. Мерить его на глаз нельзя: четыре разные ошибки дают
# правдоподобный ноль, то есть выглядят как «починено». Поэтому процедура
# лежит здесь, а не восстанавливается по памяти каждый раз.
#
#   1. pid подоболочки. `cd "$D" && ./app &` уводит в фон составной оператор,
#      и $! - pid подоболочки, а не приложения. Расход у него нулевой всегда.
#      Ниже приложение запускается напрямую, после отдельного cd.
#   2. Зависшие экземпляры. kill по неверному pid не убивает приложение, а
#      pgrep потом отдаёт старый процесс вместо нового. Ниже pid берётся у
#      своего же потомка, а по завершении процесс добивается.
#   3. Окно не выведено на экран. Пока экран погашен или окно не показано,
#      композитор не шлёт frame callbacks, цикл рендера стоит, и любой вариант
#      даёт 0%. Признак - число потоков: у работающего окна их около 17, у
#      осиротевшего без вывода на экран - 3. Ниже это проверяется.
#   4. UQ_FRAME_LOG меняет то, что измеряет: он делает сводку кадров видимой, а
#      сводка сама по себе способна держать окно перерисовывающимся. Ниже
#      переменная снимается явно.
#
# Использование:
#   tools/measure-idle.sh [каталог-дерева] [документ]
# По умолчанию - текущее дерево и testdata/test.pdf.

set -u

DIR="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
DOC="${2:-testdata/test.pdf}"
BIN="$DIR/build/src/uq-notes"

WARMUP_S=8   # прогрев: открытие документа, первые растры, устаканивание
SAMPLE_S=6   # окно замера
MIN_THREADS=8

if [ ! -x "$BIN" ]; then
    echo "нет собранного приложения: $BIN" >&2
    exit 2
fi

cd "$DIR" || exit 2
unset UQ_FRAME_LOG UQ_DEMO_NAV UQ_DEMO_INK UQ_SCREENSHOT

# Под offscreen цикл рендера крутится вхолостую независимо от того, есть ли что
# перерисовывать, и стоит при этом почти ничего: замер там показал бы 0% и на
# сломанном дереве. Требование проверяется только на настоящей платформе.
if [ "${QT_QPA_PLATFORM:-}" = "offscreen" ]; then
    echo "QT_QPA_PLATFORM=offscreen: замер простоя там бессмыслен." >&2
    echo "Под offscreen кадры выдаются вхолостую всегда, и 0% ничего не доказывает." >&2
    exit 3
fi

# Запуск напрямую: $! обязан быть pid приложения, а не подоболочки (ловушка 1).
"$BIN" "$DOC" >/dev/null 2>&1 &
APP=$!

cleanup() { kill -9 "$APP" 2>/dev/null; wait "$APP" 2>/dev/null; }
trap cleanup EXIT

sleep "$WARMUP_S"

if [ ! -r "/proc/$APP/stat" ]; then
    echo "приложение не дожило до замера (pid=$APP)" >&2
    exit 1
fi

# Двадцатое поле /proc/PID/stat - число потоков (ловушка 3).
THREADS=$(awk '{print $20}' "/proc/$APP/stat")
if [ "$THREADS" -lt "$MIN_THREADS" ]; then
    echo "окно не выведено на экран: потоков $THREADS (ожидалось не меньше $MIN_THREADS)." >&2
    echo "Замер негоден: без вывода на экран композитор не шлёт frame callbacks," >&2
    echo "цикл рендера стоит, и 0% получится на любом дереве." >&2
    exit 3
fi

read -r U1 S1 < <(awk '{print $14, $15}' "/proc/$APP/stat")
sleep "$SAMPLE_S"

if [ ! -r "/proc/$APP/stat" ]; then
    echo "приложение умерло во время замера (pid=$APP)" >&2
    exit 1
fi

read -r U2 S2 < <(awk '{print $14, $15}' "/proc/$APP/stat")
HZ=$(getconf CLK_TCK)

printf 'CPU в простое: %s%%  (pid=%s, потоков=%s, окно замера %s c)\n' \
    "$(echo "scale=1; (($U2 + $S2) - ($U1 + $S1)) * 100 / $HZ / $SAMPLE_S" | bc)" \
    "$APP" "$THREADS" "$SAMPLE_S"
