#pragma once

#include <QColor>
#include <QList>
#include <QPointF>
#include <QRectF>

// Инструмент, которым нанесён штрих.
enum class InkTool {
    Pen,
    Eraser,
};

// Закон толщины штриха от давления (ink-beauty-pass, design.md, D3). Хранится
// со штрихом: смена закона для новых штрихов не меняет толщину нанесённых.
// Значения пишутся в файл заметки - не перенумеровывать.
enum class StrokeStyle : int {
    Legacy = 0,  // W·(0.25 + 0.75p) - все штрихи, нанесённые до заострения
    Tapered = 1, // W·(0.08 + 0.92p) - тонкие заходы и выходы, как у пера rnote
};

// Точка траектории. Координаты - в системе координат страницы (точки PDF),
// а не экрана: чернила обязаны держаться содержимого страницы при любом
// масштабе и режиме отображения.
struct InkPoint
{
    QPointF position;
    // Давление в диапазоне 0..1. Отрицательное значение означает «устройство
    // давления не сообщает» - тогда штрих рисуется постоянной толщиной.
    qreal pressure = -1.0;
    // Монотонное время события в секундах: нужно фильтру One Euro, который
    // работает по реальным интервалам, а не по номерам событий.
    qreal timeSeconds = 0.0;

    bool hasPressure() const { return pressure >= 0.0; }
};

// Завершённый штрих: то, что кладётся в постоянную геометрию страницы и в файл
// заметки.
struct Stroke
{
    int page = -1;
    // Вкладыш, которому принадлежит штрих; 0 - чернила самой страницы. Точки
    // штриха вкладыша лежат в локальных координатах вкладыша: относительно
    // левого верхнего угла его рамки, в точках страницы. Поэтому изменение
    // размера вкладыша не трогает ни одной точки (design.md, D2).
    quint64 insert = 0;
    InkTool tool = InkTool::Pen;
    QColor color = QColor(20, 24, 40);
    // Толщина при полном нажиме, в точках страницы.
    qreal width = 2.4;
    // Закон толщины. По умолчанию прежний: так читаются строки заметок, где
    // закона ещё не было. Новые штрихи пера получают Tapered в DocumentCanvas.
    StrokeStyle style = StrokeStyle::Legacy;
    QList<InkPoint> points;

    bool isValid() const { return page >= 0 && points.size() >= 2; }
};

// Вкладыш: листок с белым фоном, вложенный в страницу. Рамка - в координатах
// страницы, её левый верхний угол - точка установки, где стоит значок
// свёрнутого вкладыша. Рамка может выходить за край страницы.
struct InkInsert
{
    quint64 id = 0;
    int page = -1;
    QRectF rect;
    bool open = true;

    bool isValid() const { return page >= 0 && !rect.isEmpty(); }
};
