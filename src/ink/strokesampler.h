#pragma once

#include <QList>

#include "ink/inktypes.h"
#include "ink/oneeurofilter.h"

// Приводит сырой поток событий пера к траектории, пригодной для тесселяции:
// сглаживает дрожание фильтром One Euro и ресемплит по длине дуги, чтобы
// расстояние между точками не зависело от скорости ведения.
//
// И шаг ресемплинга, и сглаживание заданы в ЭКРАННЫХ единицах, а не в
// координатах страницы. Точность у пишущего физическая - рука и экран. Если
// считать скорость и расстояния в координатах страницы, то на увеличенном
// масштабе одно и то же движение руки покрывает меньше страницы: фильтр примет
// его за медленное и сгладит сильнее, а ресемплинг положит меньше точек на
// видимую длину. Кривые превратятся в ломаные, а почерк - в нечитаемое.
//
// Ресемплинг по дуге - то, чем закрывается риск артефактов на резких изгибах:
// при равномерном шаге поворот распределяется по нескольким точкам, и стык
// нигде не получает угол, который тесселятор не сможет скруглить.
//
// Класс потоковый: точки добавляются по одной, а наружу отдаются только новые
// готовые сегменты - на этом стоит инкрементальное наращивание «мокрого»
// штриха.
class StrokeSampler
{
public:
    StrokeSampler();

    // Шаг ресемплинга в экранных единицах.
    void setSpacing(qreal spacing);
    qreal screenSpacing() const { return m_screenSpacing; }
    // Он же в координатах страницы - именно с этим шагом ложатся точки.
    qreal spacing() const { return m_screenSpacing / m_scale; }

    // Сколько экранных единиц в одной точке страницы, то есть текущий масштаб.
    // Задаётся на начало штриха и внутри штриха не меняется.
    void setScale(qreal scale);
    qreal scale() const { return m_scale; }

    void reset();

    // Добавляет сырую точку. Возвращает точки, добавившиеся к траектории.
    QList<InkPoint> append(const InkPoint &raw);
    // Завершает штрих: дотягивает траекторию до последней точки контакта, чтобы
    // штрих кончался ровно там, где перо оторвалось.
    QList<InkPoint> finish();

    const QList<InkPoint> &points() const { return m_points; }
    bool isEmpty() const { return m_points.isEmpty(); }

private:
    QList<InkPoint> emitTowards(const InkPoint &target);

    qreal m_screenSpacing = 1.2;
    qreal m_scale = 1.0;
    OneEuroPointFilter m_filter;
    OneEuroFilter m_pressureFilter;

    QList<InkPoint> m_points; // ресемплированная траектория
    InkPoint m_lastFiltered;  // последняя сглаженная точка, ещё не выданная
    // Последняя сырая точка контакта. Фильтр по своей природе отстаёт, а штрих
    // обязан кончаться там, где перо действительно оторвалось, - поэтому конец
    // берётся из сырых данных, а не из сглаженных.
    InkPoint m_lastRaw;
    bool m_hasLastFiltered = false;
    bool m_finished = false;
};
