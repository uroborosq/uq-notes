// Приводит сырой поток отсчётов пера к траектории, пригодной для тесселяции.
// Три ступени:
//
// 1. Модель пера - ink-stroke-modeler, та же, что у rnote: подавление дрожи,
//    пружинная модель положения кончика, досэмплирование по времени и догон к
//    последнему положению пера на отрыве. Поверх неё - следование за пером:
//    на быстром движении узел модели сдвигается к настоящему положению пера,
//    иначе пружина сжимала бы быстрые петли и гасила быстрые детали.
// 2. Нарезка по дуге с постоянным шагом, но точки между выходами модели лежат
//    на centripetal Catmull-Rom, а не на прямой. Модель выдаёт точки с равным
//    шагом по времени: на быстром письме между ними по десятку пикселей, и
//    нарезка по прямой дала бы грани, как бы плотно её ни резать.
// 3. Провизорный хвост: последний сегмент сплайна, которому ещё не хватает
//    следующей точки, и предсказание модели до последнего положения пера.
//    Хвост рисуется, но в штрих не попадает.
//
// И модель, и шаг нарезки работают в ЭКРАННЫХ единицах, а не в координатах
// страницы. Точность у пишущего физическая - рука и экран. Если считать
// скорость и расстояния в координатах страницы, то на увеличенном масштабе одно
// и то же движение руки покрывает меньше страницы: модель примет его за
// медленное, а нарезка положит меньше точек на видимую длину. Наружу точки
// отдаются уже в координатах страницы.
//
// Время точки - время отсчёта пера, а не момент его обработки: модель считает
// скорость по нему. Время, идущее назад, прижимается к предыдущему, а отсчёт с
// тем же временем и тем же положением отбрасывается (design.md, D2).
//
// Класс потоковый: точки добавляются по одной, а наружу отдаются только новые
// окончательные точки - на этом стоит инкрементальное наращивание «мокрого»
// штриха.
class StrokeSampler
{
public:
    StrokeSampler();
    ~StrokeSampler();

    // Шаг нарезки в экранных единицах.
    void setSpacing(qreal spacing);
    qreal screenSpacing() const { return m_screenSpacing; }
    // Он же в координатах страницы - именно с этим шагом ложатся точки.
    qreal spacing() const { return m_screenSpacing / m_scale; }

    // Сколько экранных единиц в одной точке страницы, то есть текущий масштаб.
    // Задаётся на начало штриха и внутри штриха не меняется.
    void setScale(qreal scale);
    qreal scale() const { return m_scale; }

    void reset();

    // Добавляет сырую точку. Возвращает точки, ставшие окончательными.
    QList<InkPoint> append(const InkPoint &raw);
    // Завершает штрих: догоняет модель до отрыва и дотягивает траекторию до
    // последней точки контакта, чтобы штрих кончался ровно там, где перо
    // оторвалось. Возвращает точки, ставшие окончательными.
    QList<InkPoint> finish();

    // Окончательная траектория: эти точки уже никогда не изменятся.
    const QList<InkPoint> &points() const { return m_points; }
    // Провизорный хвост после последней окончательной точки. Пересобирается
    // на каждом отсчёте и пуст после finish().
    const QList<InkPoint> &provisionalPoints() const { return m_provisional; }
    bool isEmpty() const { return m_points.isEmpty(); }

    // Касание (design.md, D5). Длительность - от первого до последнего
    // принятого отсчёта по их собственным меткам времени, в секундах.
    qreal contactDuration() const { return m_started ? m_lastInputTime : 0.0; }
    // Наибольшее отфильтрованное давление за касание; -1, если устройство
    // давления не сообщает. Давление любой точки штриха не больше него.
    qreal peakPressure() const { return m_peakPressure; }
    // Наибольшее сырое давление пера за касание, до фильтра; -1 без давления.
    // По нему отбрасывается задев: фильтр отстаёт на нарастании, и у быстрого
    // касания отфильтрованный пик ниже настоящего нажима.
    qreal peakRawPressure() const { return m_peakRawPressure; }

    // Фильтр давления с параметрами сэмплера. Открыт для эталонов
    // tst_strokesampler: давление точки сверяется с отфильтрованным давлением
    // пера в момент точки (ink-beauty-pass, design.md, D2).
    static OneEuroFilter makePressureFilter();

private:
    // Следование за пером на быстром движении. Модель - пружина, и на быстром
    // движении она отстаёт от пера на десяток пикселей: быстрая окружность
    // сжимается, быстрый зубец сглаживается. Поэтому узел модели сдвигается к
    // положению пера в тот же момент времени - тем сильнее, чем быстрее
    // движение. Скорость - сглаженная скорость модели, доля - гладкая функция
    // от неё: резкое переключение между пружиной и отсчётами само рисовало бы
    // излом там, где перо разгоняется.
    struct FollowState
    {
        qreal speed = 0.0;
        qreal time = 0.0;
        bool primed = false;
    };
    InkPoint followedNode(const ink::stroke_model::Result &result, FollowState &state) const;
    // Положение пера в момент time по отсчётам: линейно между соседними.
    QPointF rawAt(qreal time) const;
    // Отфильтрованное давление пера в момент time, линейно между соседними
    // отсчётами. Давление узла берётся отсюда, по времени узла, а не с
    // проекции отстающей пружины на ломаную отсчётов: при следовании за пером
    // положение узла - перо в момент t, а давление пружины примерно на 20 мс
    // старше, и спад нажима на отрыве терялся (ink-beauty-pass, design.md, D2).
    qreal pressureAt(qreal time) const;

    void appendNode(const ink::stroke_model::Result &result);
    QList<InkPoint> emitSettled(bool toEnd);
    void rebuildProvisional();

    // Точка модели (экранные единицы, время от начала штриха) - в координаты
    // страницы и абсолютное время.
    InkPoint toPage(const InkPoint &node) const;
    // Проходит сегмент сплайна nodes[k] -> nodes[k + 1] мелкими шагами и
    // отдаёт промежуточные точки. Недостающие соседи отражаются. Параметр не
    // называется emit: это макрос Qt, он раскрывается в пустоту и молча
    // съедает вызов.
    template <typename Sink>
    void flattenSegment(const QList<InkPoint> &nodes, int k, Sink sink) const;
    // Идёт от last к target шагами ровно в spacing, линейно интерполируя
    // давление и время.
    void walkTowards(InkPoint &last, const InkPoint &target, QList<InkPoint> &out) const;

    qreal m_screenSpacing = 1.2;
    qreal m_scale = 1.0;

    std::unique_ptr<ink::stroke_model::StrokeModeler> m_modeler;
    std::vector<ink::stroke_model::Result> m_results;
    std::vector<ink::stroke_model::Result> m_prediction;
    OneEuroFilter m_pressureFilter;

    bool m_started = false;
    bool m_finished = false;
    qreal m_timeOrigin = 0.0;
    qreal m_lastInputTime = 0.0;   // от начала штриха, после прижима
    QPointF m_lastInputScreen;     // положение последнего отсчёта на экране
    qreal m_lastInputPressure = -1.0;
    qreal m_peakPressure = -1.0;
    qreal m_peakRawPressure = -1.0;
    // Последняя сырая точка контакта. Модель по своей природе отстаёт, а штрих
    // обязан кончаться там, где перо действительно оторвалось, - поэтому конец
    // берётся из сырых данных, а не из модели.
    InkPoint m_lastRaw;

    FollowState m_follow;
    // Последние отсчёты пера для rawAt и pressureAt: экранные единицы,
    // отфильтрованное давление, время от начала штриха. Узлы модели никогда не
    // бывают старше нескольких отсчётов.
    QList<InkPoint> m_rawHistory;

    // Выход модели, ещё нужный сплайну: экранные единицы, время от начала
    // штриха. m_nextSegment - первый сегмент, по которому ещё не нарезаны
    // окончательные точки; узлы до m_nextSegment - 1 отбрасываются.
    QList<InkPoint> m_nodes;
    int m_nextSegment = 0;

    QList<InkPoint> m_points;      // окончательная траектория, координаты страницы
    QList<InkPoint> m_provisional; // провизорный хвост, координаты страницы
};
